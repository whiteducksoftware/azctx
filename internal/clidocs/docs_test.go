func TestDocumentationFreshness(t *testing.T) {
	directory := testutil.WorkDir(t)
	if err := clidocs.Sync(directory, false); err != nil {
		t.Fatal(err)
	}
	if err := clidocs.Sync(directory, true); err != nil {
		t.Fatalf("identical second generation is stale: %v", err)
	}
	for _, mutation := range []string{"changed", "missing", "extra"} {
		t.Run(mutation, func(t *testing.T) {
			directory := testutil.WorkDir(t)
			if err := clidocs.Sync(directory, false); err != nil {
				t.Fatal(err)
			}
			name := filepath.Join(directory, "azctx.md")
			wantError := "stale CLI documentation:"
			switch mutation {
			case "changed":
				if err := os.WriteFile(name, []byte("outdated help\n"), 0o600); err != nil {
					t.Fatal(err)
				}
			case "missing":
				if err := os.Remove(name); err != nil {
					t.Fatal(err)
				}
			case "extra":
				wantError = "unexpected CLI documentation:"
				if err := os.WriteFile(filepath.Join(directory, "azctx_obsolete.md"), nil, 0o600); err != nil {
					t.Fatal(err)
				}
			}
			if err := clidocs.Sync(directory, true); err == nil || !strings.Contains(err.Error(), wantError) {
				t.Fatalf("want %q, got %v", wantError, err)
			}
		})
	}
}

func TestDocumentationFreshnessRejectsByteChanges(t *testing.T) {
	for _, mutation := range []struct {
		name   string
		change func([]byte) []byte
	}{
		{"edited heading", func(data []byte) []byte {
			return bytes.Replace(data, []byte("# azctx\n"), []byte("# outdated azctx\n"), 1)
		}},
		{"CRLF", func(data []byte) []byte {
			return bytes.ReplaceAll(data, []byte("\n"), []byte("\r\n"))
		}},
		{"trailing newline", func(data []byte) []byte {
			return append(data, '\n')
		}},
	} {
		t.Run(mutation.name, func(t *testing.T) {
			directory := testutil.WorkDir(t)
			if err := clidocs.Sync(directory, false); err != nil {
				t.Fatal(err)
			}
			root, err := os.OpenRoot(directory)
			if err != nil {
				t.Fatal(err)
			}
			defer func() {
				if err := root.Close(); err != nil {
					t.Error(err)
				}
			}()
			original, err := root.ReadFile("azctx.md")
			if err != nil {
				t.Fatal(err)
			}
			changed := mutation.change(bytes.Clone(original))
			if bytes.Equal(original, changed) {
				t.Fatal("mutation did not change generated bytes")
			}
			if err := root.WriteFile("azctx.md", changed, 0o600); err != nil {
				t.Fatal(err)
			}
			if err := clidocs.Sync(directory, true); err == nil || !strings.Contains(err.Error(), "stale CLI documentation:") {
				t.Fatalf("changed bytes must be stale, got %v", err)
			}
			after, err := root.ReadFile("azctx.md")
			if err != nil || !bytes.Equal(after, changed) {
				t.Fatalf("freshness check rewrote documentation: %v", err)
			}
		})
	}
}

