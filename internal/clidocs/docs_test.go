func TestDocumentationFreshnessOnCRLFCheckout(t *testing.T) {
	directory := testutil.WorkDir(t)
	entries, err := os.ReadDir("../../docs/cli")
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) == 0 {
		t.Fatal("committed CLI reference missing")
	}
	args := []string{
		"-c", "core.autocrlf=true", "-c", "core.eol=crlf",
		"checkout-index", "--prefix=" + filepath.ToSlash(directory) + "/", "--",
	}
	for _, entry := range entries {
		args = append(args, "docs/cli/"+entry.Name())
	}
	command := exec.Command("git", args...)
	command.Dir = filepath.Join("..", "..")
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("Git CRLF checkout failed: %v\n%s", err, output)
	}
	if err := clidocs.Sync(filepath.Join(directory, "docs", "cli"), true); err != nil {
		t.Fatal(err)
	}
	t.Logf("all %d generated pages remain byte-exact after Git core.autocrlf=true checkout", len(entries))
}

func TestDocumentationCanonicalWhitespace(t *testing.T) {
	directory := testutil.WorkDir(t)
	if err := clidocs.Sync(directory, false); err != nil {
		t.Fatal(err)
	}
	names, err := filepath.Glob(filepath.Join(directory, "*.md"))
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range names {
		data, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.HasSuffix(data, []byte("\n")) || bytes.HasSuffix(data, []byte("\n\n")) || bytes.ContainsRune(data, '\r') {
			t.Fatalf("%s must have canonical LF and exactly one trailing newline", name)
		}
	}
}
